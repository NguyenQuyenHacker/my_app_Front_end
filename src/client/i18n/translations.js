export const SUPPORTED_LANGS = ["vi", "en"];

export function getMessage(lang, key) {
  const parts = key.split(".");
  let node = translations[lang] || translations.vi;
  for (const p of parts) {
    if (node && typeof node === "object" && p in node) {
      node = node[p];
    } else {
      // fallback to VI if missing in current lang
      if (lang !== "vi") return getMessage("vi", key);
      return key;
    }
  }
  return typeof node === "string" ? node : key;
}
